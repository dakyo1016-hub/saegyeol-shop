if (typeof window !== "undefined") {
  try {
    const adminCatalog = JSON.parse(localStorage.getItem("saegyeol_admin_catalog_v1")) || {};
    products.forEach((product) => {
      const override = adminCatalog[product.id];
      if (override) Object.assign(product, override, { id: product.id });
      if (product.stock == null) product.stock = Math.max(4, 34 - product.id);
      if (product.active == null) product.active = true;
    });
    Object.values(adminCatalog).filter((item) => item?._isNew && !products.some((product) => product.id === Number(item.id))).forEach((item) => products.push({ ...item, id: Number(item.id) }));
  } catch {
    products.forEach((product) => { product.stock ??= Math.max(4, 34 - product.id); product.active ??= true; });
  }
}

export const getProduct = (id) => products.find((product) => product.id === Number(id)) || products[0];
